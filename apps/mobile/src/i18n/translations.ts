export function localizeSubjectName(
  rawName?: string | null,
  lang: AppLanguage = 'uz',
  subjectId?: string | null,
): string {
  const byId = subjectId ? SUBJECT_TRANSLATIONS[subjectId.trim().toLowerCase()] : undefined;
  if (byId) return byId[lang];
  const key = String(rawName || '').trim().toLowerCase();
  if (key && SUBJECT_TRANSLATIONS[key]) {
    return SUBJECT_TRANSLATIONS[key][lang];
  }
  return rawName || SUBJECT_TRANSLATIONS.sub_eng[lang];
}

export function localizeBookType(type?: string | null, lang: AppLanguage = 'uz'): string {
  const dict = TRANSLATIONS[lang].grades;
  switch (String(type || '').toUpperCase()) {
    case 'WORKBOOK':
      return dict.bookTypeWorkbook;
    case 'TEACHER_BOOK':
      return dict.bookTypeTeacher;
    case 'AUDIO':
      return dict.bookTypeAudio;
    default:
      return dict.bookTypeStudent;
  }
}

export function localizeGradeLabel(gradeId: number | string, lang: AppLanguage = 'uz'): string {
  return TRANSLATIONS[lang].common.gradeUnit.replace('{n}', String(gradeId));
}

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : `{${k}}`,
  );
}
